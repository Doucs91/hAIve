import { z } from "zod";

export const MemoryScopeSchema = z.enum(["personal", "team", "module", "shared"]);

export const MemoryStatusSchema = z.enum([
  "draft",
  "proposed",
  "validated",
  "deprecated",
  "stale",
  "rejected",
]);

export const MemoryTypeSchema = z.enum([
  "convention",
  "decision",
  "gotcha",
  "architecture",
  "glossary",
  "skill",         // reusable procedure/playbook for a recurring task (feedforward harness guide)
  "attempt",       // failed approach — "tried X, failed because Y, use Z instead"
  "session_recap", // end-of-session summary: goal / accomplished / discoveries / next steps
]);

export const AnchorSchema = z.object({
  commit: z.string().optional(),
  paths: z.array(z.string()).default([]),
  symbols: z.array(z.string()).default([]),
});

/**
 * An executable check derived from a memory — the "feedback computational" layer.
 *
 * A `gotcha`/`attempt` is normally feedforward (text the agent reads). A sensor turns
 * that lesson into a deterministic check: when a touched file matches `pattern`, the
 * memory's warning fires regardless of semantic ranking. This closes the harness loop —
 * a documented mistake becomes a permanent guardrail.
 *
 * Phase 1 implements `kind: "regex"` only. `shell`/`test` are reserved for a later phase
 * (they require I/O and must run from the CLI, not core).
 */
export const SensorSchema = z.object({
  kind: z.enum(["regex", "ast", "shell", "test"]).default("regex"),
  /**
   * kind=regex: regex source, matched against added diff lines / file content.
   * kind=ast: an ast-grep structural pattern (e.g. `stripe.paymentIntents.create($$$)`) — matched
   * on the AST of changed files, so comments and string literals can never false-positive. Requires
   * the optional `@ast-grep/napi` engine; without it the sensor is unrunnable (warn, never block).
   */
  pattern: z.string().optional(),
  /** kind=ast: full ast-grep Rule object (`kind`, `inside`, `has`, `not`, `all`, `any`, …). */
  rule: z.record(z.unknown()).optional(),
  /** kind=ast: explicit language name for extensionless/non-standard files (e.g. python, go). */
  language: z.string().optional(),
  /**
   * Optional "correct-usage" regex (kind=regex). When `pattern` (the risky call) matches but this
   * regex ALSO appears within a small window around the match, the catch is SUPPRESSED — the diff
   * already includes the required companion. Encodes "X without Y": `pattern`=X (e.g. the API call),
   * `absent`=Y (e.g. the required option). This is what lets an autogenerated sensor discriminate the
   * faulty usage from the correct one instead of firing on every call — and makes it safe to promote.
   */
  absent: z.string().optional(),
  /** Regex flags (e.g. "i", "m"). Ignored for non-regex kinds. */
  flags: z.string().optional(),
  /**
   * kind=regex only: flip the sensor into a REQUIRED-PRESENCE invariant. `pattern` then names a line
   * that must REMAIN present in the anchored file's final content; the sensor FIRES when a change
   * removes it. A normal regex sensor scans ADDED lines and so structurally cannot see a deletion —
   * this catches the "someone deleted the critical line" class (e.g. a `TimeZone.setDefault(UTC)`
   * guard) that a diff-of-additions sensor misses (field report §3.5).
   */
  require_present: z.boolean().optional(),
  /** Shell/test command to run (for kind=shell|test). Executed by the CLI, never by core. */
  command: z.string().optional(),
  /** Max runtime for kind=shell|test commands (default 120000). The executor kills on expiry. */
  timeout_ms: z.number().int().positive().optional(),
  /** Glob-ish path prefixes the sensor applies to. Falls back to the memory's anchor paths when empty. */
  paths: z.array(z.string()).default([]),
  /**
   * Glob-ish paths the sensor must NOT fire on, even when they fall inside `paths`. Lets a
   * production-only lesson (e.g. "no `any`") skip test doubles and fixtures without narrowing its
   * scope file by file — the missing negation that made `paths: ['**']` fire on every `.test.ts`
   * (field report 2026-09-02 §3.2). A lesson that IS about tests (e.g. "no `LocalDate.now()` in a
   * test") simply leaves this empty, so it still fires there.
   */
  exclude: z.array(z.string()).optional(),
  /** LLM-facing self-correction message: what was done wrong and what to do instead. */
  message: z.string().min(1),
  /**
   * Optional provenance: the real incident this sensor guards against — a ticket ref, a prod
   * incident id, a date ("prod #442", "INC-1029", "2026-06 refund overcharge"). This is the
   * behaviour-harness link a plain test can't carry: it turns "a test failed" into "this reproduces
   * the incident the test exists to prevent". Surfaced in the block message and the prevention receipt.
   */
  incident: z.string().optional(),
  /**
   * kind=shell|test only: the oracle was PROVEN to fail (RED) on the incident state at arming time
   * (`sensors propose --red-ref`): the command passed on the presumed-correct tree AND failed on
   * the replayed incident tree. Distinguishes "a test is routed" from "the test demonstrably
   * catches the incident". Surfaced in the prevention receipt.
   */
  red_proven: z.boolean().optional(),
  /** `warn` surfaces in review; `block` can hard-block the commit (only when the gate opts in). */
  severity: z.enum(["warn", "block"]).default("warn"),
  /** True when Hivelore generated this sensor automatically (vs. hand-authored). */
  autogen: z.boolean().default(false),
  /** ISO timestamp of the last time this sensor matched a diff. */
  last_fired: z.string().nullable().default(null),
  /**
   * ISO timestamp of the last manual `sensors promote` back to block. Health assessment ignores
   * ledger evaluations older than this — without it, a promoted sensor whose oracle was FIXED is
   * re-quarantined on the next commit for up to 30 days (the stale flaps are still in the window),
   * making the promotion promised by the quarantine note a no-op.
   */
  promoted_at: z.string().optional(),
});

/**
 * Progressive-disclosure activation triggers for a `skill` memory.
 *
 * A skill is a reusable playbook (feedforward harness guide). Injecting every skill
 * on every briefing bloats the context and dilutes signal (the "instruction budget"
 * problem). An `activation` block makes a skill surface ONLY when it is relevant:
 * its keywords match the task, or its globs match the files being edited. A skill
 * that defines `activation` and matches none of it is suppressed from the briefing;
 * a skill with no `activation` block keeps the legacy always-eligible behavior.
 */
export const ActivationSchema = z.object({
  /** Case-insensitive substrings matched against the task text. */
  keywords: z.array(z.string()).default([]),
  /** Glob-ish path patterns matched against the files being edited. */
  globs: z.array(z.string()).default([]),
  /** Always activate (rare — for truly universal playbooks). */
  always: z.boolean().default(false),
});

const IsoDateString = z
  .union([z.string(), z.date()])
  .transform((v) => (v instanceof Date ? v.toISOString() : v))
  .pipe(z.string().datetime());

export const MemoryFrontmatterSchema = z
  .object({
    id: z.string().min(1),
    scope: MemoryScopeSchema.default("personal"),
    module: z.string().optional(),
    type: MemoryTypeSchema,
    status: MemoryStatusSchema.default("draft"),
    anchor: AnchorSchema.default({ paths: [], symbols: [] }),
    /** Optional executable check derived from this memory (feedback computational layer). */
    sensor: SensorSchema.optional(),
    /** Optional progressive-disclosure triggers — only meaningful for `type: skill`. */
    activation: ActivationSchema.optional(),
    tags: z.array(z.string()).default([]),
    domain: z.string().optional(),
    author: z.string().optional(),
    created_at: IsoDateString,
    expires_when: z.string().nullable().default(null),
    verified_at: z.string().nullable().default(null),
    stale_reason: z.string().nullable().default(null),
    related_ids: z.array(z.string()).default([]),
    last_read_at: z.string().nullable().default(null),
    topic: z.string().optional(),          // stable key for upsert — same topic in same scope → update instead of create
    revision_count: z.number().int().min(0).default(0), // incremented each time a topic upsert occurs
    /**
     * When true, the AI MUST NOT act on this memory autonomously.
     * It must surface the information to the human developer and wait
     * for explicit confirmation before modifying any code.
     * Used for cross-repo breaking changes, dependency bumps, contract diffs.
     */
    requires_human_approval: z.boolean().default(false),
    /**
     * Provenance of the memory's `validated` status — who/what last trusted it:
     *   "human"  — a person explicitly approved it (CLI `memory approve`)
     *   "agent"  — an AI agent explicitly approved it (MCP `mem_approve`)
     *   "auto"   — an automatic rule trusted it without review (auto-promotion by read
     *              count/time, or `defaultStatus: validated` on creation)
     * null when the memory is not yet validated, or on legacy memories written before this field.
     * Lets a human distinguish reviewed knowledge from AI/auto-trusted knowledge.
     */
    validated_by: z.enum(["human", "agent", "auto"]).nullable().default(null),
    /**
     * Does this memory describe code that EXISTS today, or a decision not yet built? Orthogonal to
     * `confidence`/`status`: a `planned` decision can be fully trusted AS a decision while being false
     * AS a description of the current code. Surfaced distinctly in briefings so an agent does not write
     * code against a cookie/route/Node version that was only decided, never implemented (field report §3.3).
     *   applied   — reflected in the code now (the default when omitted)
     *   planned   — decided/intended, NOT yet implemented
     *   abandoned — considered and rejected; kept so it is not re-attempted
     */
    lifecycle: z.enum(["applied", "planned", "abandoned"]).optional(),
  })
  .refine(
    (data) => data.scope !== "module" || !!data.module,
    { message: "module name is required when scope is 'module'", path: ["module"] },
  );

// Additional fields for cross-repo provenance (stored in frontmatter of imported memories)
export const CrossRepoProvenanceSchema = z.object({
  source_name: z.string(),    // the crossRepoSources name from haive.config.json
  source_path: z.string(),    // original file path in the source repo
  source_id: z.string(),      // original memory id
  imported_at: z.string(),    // ISO timestamp of import
}).optional();
